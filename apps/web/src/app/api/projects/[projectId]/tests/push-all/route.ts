interface Bundle { path: string; content: string; count: number; kind: string }

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 50) || "tests";

/**
 * Group tests into ONE file per (kind, suite). Within a file, each test's body is
 * wrapped in a block `{ … }` so its top-level consts are isolated (no cross-test
 * collisions), and all `import` lines are de-duplicated and hoisted to the top.
 * A header comment explains how to install & run.
 */
/** Cap tests per file so a single big suite splits into a few reviewable files. */
const MAX_TESTS_PER_FILE = 25;

function bundleSpecs(tests: { name: string; suite: string | null; kind: string; spec_content: string }[]): Bundle[] {
  const groups = new Map<string, typeof tests>();
  for (const t of tests) {
    const key = `${t.kind}::${t.suite || "default"}`;
    (groups.get(key) ?? groups.set(key, []).get(key)!).push(t);
  }

  const importRe = /^\s*import\s.+?;?\s*$/gm;
  const bundles: Bundle[] = [];
  for (const [key, group] of groups) {
    const [kind, suite] = key.split("::");
    const isApi = kind === "api";
    // Split a large suite into chunks: suite.spec.ts, suite-2.spec.ts, …
    const chunks: typeof group[] = [];
    for (let i = 0; i < group.length; i += MAX_TESTS_PER_FILE) chunks.push(group.slice(i, i + MAX_TESTS_PER_FILE));

    chunks.forEach((chunk, ci) => {
      const imports = new Set<string>();
      const blocks: string[] = [];
      for (const t of chunk) {
        const code = t.spec_content ?? "";
        for (const m of code.match(importRe) ?? []) imports.add(m.trim());
        const body = code.replace(importRe, "").trim();
        blocks.push(`// ── ${t.name} ──\n{\n${body}\n}`);
      }
      const fileSlug = ci === 0 ? slug(suite) : `${slug(suite)}-${ci + 1}`;
      const path = `${isApi ? "tests/api/" : "tests/"}${fileSlug}.spec.ts`;
      const header = `/**
 * Verity ${isApi ? "API" : "UI"} tests — suite: ${suite}${chunks.length > 1 ? ` (part ${ci + 1}/${chunks.length})` : ""}
 * Generated by Verity (https://verity-kappa-ebon.vercel.app).
 *
 * Run all:        npx playwright test
 * Run this file:  npx playwright test ${path}
 * Install once:   npm install && npx playwright install
 * ${isApi ? "Set API base/secrets via env (e.g. BASE_URL, API_TOKEN)." : "Point at an environment with BASE_URL, e.g. BASE_URL=https://your-app.com npx playwright test."}
 */`;
      const content = `${header}\n${[...imports].join("\n")}\n\n${blocks.join("\n\n")}\n`;
      bundles.push({ path, content, count: chunk.length, kind });
    });
  }
  return bundles;
}

function readme(bundles: Bundle[]): string {
  const total = bundles.reduce((n, b) => n + b.count, 0);
  const hasApi = bundles.some((b) => b.kind === "api");
  const hasUi = bundles.some((b) => b.kind !== "api");
  return `# Verity tests

These Playwright tests were generated in [Verity](https://verity-kappa-ebon.vercel.app) and opened as this pull request.

## What's here
- ${total} test${total === 1 ? "" : "s"} bundled into ${bundles.length} file${bundles.length === 1 ? "" : "s"} — one per suite.
${hasUi ? "- `tests/*.spec.ts` — UI tests (run in a browser).\n" : ""}${hasApi ? "- `tests/api/*.spec.ts` — API tests (HTTP request tests, no browser).\n" : ""}- \`playwright.config.ts\` — added only if your repo didn't already have one.
- \`.github/workflows/verity-tests.yml\` — runs these on every PR/push (added only if missing).

## Run them locally
\`\`\`bash
npm install
npx playwright install        # one-time: download browsers
BASE_URL="https://your-app.com" npx playwright test
\`\`\`
Run a single test: \`npx playwright test tests/<file>.spec.ts\`.
Watch it in a browser: \`npx playwright test --headed\` or \`npx playwright test --ui\`.

## In CI
The included workflow runs \`npx playwright test\` on every pull request. Set a
\`BASE_URL\` repo secret (Settings → Secrets → Actions) so tests hit the right
environment. Results show up as a check on the PR.

> Credentials: tests that need login read \`TEST_USERNAME\` / \`TEST_PASSWORD\` from
> the environment unless the values were baked in at generation time. Add them as
> CI secrets if needed.
`;
}

/**
 * Push ALL of a project's tests to the repo in ONE pull request — one commit
 * containing every spec file (via the git trees API), then a PR. Much better
 * than one PR per test.
 */
export async function POST(_req: NextRequest, { params }: { params: Promise<{ projectId: string }> }) {
  const { projectId } = await params;
  const supabase = await createClient();

  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return NextResponse.json({ error: "Not authenticated" }, { status: 401 });

  const { data: project } = await supabase
    .from("projects").select("id, repo, default_branch, github_installation_id").eq("id", projectId).maybeSingle();
  if (!project) return NextResponse.json({ error: "Project not found" }, { status: 404 });

  const repo = parseRepo(project.repo);
  if (!repo) return NextResponse.json({ error: "Link a GitHub repo to this project first." }, { status: 400 });

  const { data: tests } = await supabase
    .from("tests").select("name, suite, kind, spec_content").eq("project_id", projectId).neq("status", "archived");
  if (!tests || tests.length === 0) return NextResponse.json({ error: "No tests to push." }, { status: 400 });

  // Bundle tests into ONE file per (kind, suite) instead of one file per test —
  // 100 tests should be a handful of files, not 100. Each test is block-scoped so
  // its top-level consts can't collide; imports are de-duped and hoisted.
  const bundles = bundleSpecs(tests);

  const installationId = await resolveInstallationId(repo.owner, project.github_installation_id);
  if (!installationId) return NextResponse.json({ error: "Install the Verity GitHub App on this repo first." }, { status: 400 });
  const octokit = await installationOctokit(installationId);
  if (!octokit) return NextResponse.json({ error: "GitHub App not configured." }, { status: 503 });

  try {
    const base = project.default_branch || "main";
    const baseRef = await octokit.request("GET /repos/{owner}/{repo}/git/ref/{ref}", { owner: repo.owner, repo: repo.repo, ref: `heads/${base}` });
    const baseSha = (baseRef.data as { object: { sha: string } }).object.sha;
    const baseCommit = await octokit.request("GET /repos/{owner}/{repo}/git/commits/{commit_sha}", { owner: repo.owner, repo: repo.repo, commit_sha: baseSha });
    const baseTreeSha = (baseCommit.data as { tree: { sha: string } }).tree.sha;

    // Build the tree: bundled spec files, a how-to-run README, and (only if
    // absent) a Playwright config + CI workflow so the repo can actually run them.
    const files: { path: string; content: string }[] = bundles.map((b) => ({ path: b.path, content: b.content }));
    files.push({ path: "tests/README-verity.md", content: readme(bundles) });
    const [hasConfigTs, hasConfigJs, hasWorkflow] = await Promise.all([
      fileExists(octokit, repo.owner, repo.repo, "playwright.config.ts", base),
      fileExists(octokit, repo.owner, repo.repo, "playwright.config.js", base),
      fileExists(octokit, repo.owner, repo.repo, ".github/workflows/verity-tests.yml", base),
    ]);
    if (!hasConfigTs && !hasConfigJs) files.push({ path: "playwright.config.ts", content: PLAYWRIGHT_CONFIG });
    if (!hasWorkflow) files.push({ path: ".github/workflows/verity-tests.yml", content: WORKFLOW });

    const tree = await octokit.request("POST /repos/{owner}/{repo}/git/trees", {
      owner: repo.owner, repo: repo.repo, base_tree: baseTreeSha,
      tree: files.map((f) => ({ path: f.path, mode: "100644" as const, type: "blob" as const, content: f.content })),
    });

    const commit = await octokit.request("POST /repos/{owner}/{repo}/git/commits", {
      owner: repo.owner, repo: repo.repo,
      message: `Add ${tests.length} Verity test${tests.length === 1 ? "" : "s"}`,
      tree: (tree.data as { sha: string }).sha,
      parents: [baseSha],
    });

    const branch = `verity/tests-${Date.now().toString(36)}`;
    await octokit.request("POST /repos/{owner}/{repo}/git/refs", { owner: repo.owner, repo: repo.repo, ref: `refs/heads/${branch}`, sha: (commit.data as { sha: string }).sha });

    const pr = await octokit.request("POST /repos/{owner}/{repo}/pulls", {
      owner: repo.owner, repo: repo.repo,
      title: `Verity: ${tests.length} test${tests.length === 1 ? "" : "s"}`,
      head: branch, base,
      body: `${tests.length} Playwright test(s) generated in [Verity](https://verity-kappa-ebon.vercel.app), bundled into ${bundles.length} file(s).\n\n` +
        `**Files**\n` +
        bundles.map((b) => `- \`${b.path}\` (${b.count} test${b.count === 1 ? "" : "s"})`).join("\n") +
        `\n- \`tests/README-verity.md\` — how to run` +
        (!hasConfigTs && !hasConfigJs ? `\n- \`playwright.config.ts\`` : ``) +
        (!hasWorkflow ? `\n- \`.github/workflows/verity-tests.yml\` — runs them on every PR` : ``) +
        `\n\n**Run locally**\n\`\`\`bash\nnpm install && npx playwright install\nBASE_URL="https://your-app.com" npx playwright test\n\`\`\`\n` +
        `See \`tests/README-verity.md\` for details. Once merged, the workflow runs every PR (set a \`BASE_URL\` repo secret).`,
    });

    return NextResponse.json({ ok: true, pr_url: (pr.data as { html_url: string }).html_url, count: tests.length, files: bundles.length });
  } catch (err) {
    const status = (err as { status?: number })?.status;
    const msg = err instanceof Error ? err.message : "push failed";
    if (status === 403 || /Resource not accessible/i.test(msg)) {
      return NextResponse.json({ error: "GitHub 403 — the installation must re-accept the App's 'Contents: write' permission (GitHub → Settings → Applications → Verity by QAShift → Configure → approve)." }, { status: 403 });
    }
    return NextResponse.json({ error: `GitHub: ${msg}` }, { status: 500 });
  }
}

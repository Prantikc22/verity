function parseRepo(repo: string | null): { owner: string; repo: string } | null {
  if (!repo) return null;
  const c = repo.replace(/^https?:\/\/(www\.)?github\.com\//i, "").replace(/\.git$/i, "").replace(/\/+$/, "").trim().replace(/\s+/g, "/");
  const [owner, name] = c.split("/");
  return owner && name ? { owner, repo: name } : null;
}

async function resolveInstallationId(owner: string, explicit: number | null): Promise<number | null> {
  if (explicit) return explicit;
  const admin = createAdminClient();
  const { data } = await admin.from("github_installations").select("installation_id").eq("account_login", owner).eq("suspended", false).maybeSingle();
  return data?.installation_id ?? null;
}

type Octo = NonNullable<Awaited<ReturnType<typeof installationOctokit>>>;

/** Does a path already exist on the base branch? Avoids clobbering the user's config/workflow. */
async function fileExists(octokit: Octo, owner: string, repo: string, path: string, ref: string): Promise<boolean> {
  try {
    await octokit.request("GET /repos/{owner}/{repo}/contents/{path}", { owner, repo, path, ref });
    return true;
  } catch {
    return false;
  }
}

